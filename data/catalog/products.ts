/** Standard volume-break table, scaled from a base unit price. */
function tiers(base: number): PriceTier[] {
  return [
    { minQty: 10, unit: base },
    { minQty: 25, unit: round(base * 0.89) },
    { minQty: 50, unit: round(base * 0.77) },
    { minQty: 100, unit: round(base * 0.68) },
    { minQty: 250, unit: round(base * 0.59) },
  ];
}
function round(n: number): number {
  return Math.round(n * 2) / 2; // nearest €0.50
}

